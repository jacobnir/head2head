/**
 * `npm run deploy`: build and ship the hosted copy to Vercel (project `in-house`).
 *
 * Deploys a staged folder, never the repo: just the built site, the /api/ranks function
 * and the player list it needs. So `.env` (the Riot key) can't ride along by accident.
 * The key lives in Vercel as the RIOT_API_KEY environment variable instead.
 *
 * The site code's hash comes from `.env.production.local` (gitignored), which Vite reads
 * for production builds only, so `npm run dev` stays code-free.
 *
 *   npm run deploy            → production
 *   npm run deploy -- --dry   → stage only, print what would ship
 */
import { execSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const STAGE = join(ROOT, 'tmp', 'deploy')
const DRY = process.argv.includes('--dry')
const run = (cmd, cwd = ROOT) => execSync(cmd, { cwd, stdio: 'inherit' })

const fail = (msg) => { console.error(`\n❌ ${msg}\n`); process.exit(1) }

if (!existsSync(join(ROOT, '.vercel', 'project.json')))
  fail('Not linked to Vercel yet. Run: npx vercel link --project in-house')
const envProd = join(ROOT, '.env.production.local')
if (!existsSync(envProd) || !/^VITE_SITE_CODE_SHA256=\w{64}\s*$/m.test(readFileSync(envProd, 'utf8')))
  console.warn('⚠ No VITE_SITE_CODE_SHA256 in .env.production.local: the site will have NO code gate.\n')

console.log('🔨 building…')
run('npm run build')

console.log('\n📦 staging…')
rmSync(STAGE, { recursive: true, force: true })
mkdirSync(join(STAGE, 'api'), { recursive: true })
cpSync(join(ROOT, 'dist'), STAGE, { recursive: true })
cpSync(join(ROOT, 'api', 'ranks.js'), join(STAGE, 'api', 'ranks.js'))
cpSync(join(ROOT, '.vercel'), join(STAGE, '.vercel'), { recursive: true })
writeFileSync(join(STAGE, 'package.json'), JSON.stringify({ private: true, type: 'module' }, null, 2) + '\n')

// Riot IDs exactly as the last sync resolved and cleaned them.
const stats = JSON.parse(readFileSync(join(ROOT, 'src', 'data', 'playerStats.json'), 'utf8').replace(/^﻿/, ''))
const players = Object.entries(stats.players).map(([id, p]) => ({ id, riotId: p.riotId, platform: p.platform }))
writeFileSync(join(STAGE, 'api', '_players.js'),
  `// Generated by scripts/deploy.mjs from src/data/playerStats.json. Do not edit.\nexport const PLAYERS = ${JSON.stringify(players, null, 2)}\n`)

// Belt and braces: nothing that looks like a Riot key may leave this machine.
const walk = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f)
  return statSync(p).isDirectory() ? walk(p) : [p]
})
for (const file of walk(STAGE)) {
  if (/\.(js|json|html|css|map)$/.test(file) && readFileSync(file, 'utf8').includes('RGAPI-')) fail(`Riot key found in ${file}. Aborting.`)
}
console.log(`   ${players.length} players for /api/ranks, ${walk(STAGE).length} files staged`)

if (DRY) { console.log(`\n(dry run) staged at ${STAGE}`); process.exit(0) }

console.log('\n🚀 deploying…')
run('npx --yes vercel@latest deploy --prod --yes', STAGE)
